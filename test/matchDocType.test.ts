import { test } from 'node:test';
import assert from 'node:assert/strict';

import { matchDocType } from '../src/lib/domain/docTypes';

/**
 * คนพิมพ์จากมือถือ ระหว่างขับรถ ระหว่างประชุม — พิมพ์ผิดเป็นเรื่องปกติ
 * ระบบที่เข้าใจแค่คำที่สะกดถูก คือระบบที่ใช้ได้เฉพาะตอนคนไม่รีบ
 */
const HITS: Array<[string, string]> = [
  // สะกดถูก
  ['วีซ่า 12/10/2570', 'visa'],
  ['พาสปอร์ตหมดอายุ 30/6/69', 'passport'],
  ['หนังสือเดินทาง', 'passport'],
  ['พ.ร.บ. หมดอายุ 30 มิ.ย. 69', 'cmi'],
  ['ภาษีรถ 1กก1234 หมด 31/12/69', 'vehicle_tax'],
  ['ใบขับขี่หมดอายุพรุ่งนี้', 'driving_license'],
  ['บัตรประชาชน', 'national_id'],
  ['ตรวจสภาพรถ', 'vehicle_inspection'],
  ['ใบอนุญาตทำงาน', 'work_permit'],
  ['สัญญาเช่าห้อง 31/12/69', 'lease'],

  // พิมพ์ผิด / ตัดวรรณยุกต์ / ทับศัพท์คนละแบบ
  ['พาสพอต 12/10/2570', 'passport'],
  ['พาสพอร์ต', 'passport'],
  ['พาสปอต', 'passport'],
  ['วีซา 12/10/70', 'visa'],
  ['พรบ 30/6/69', 'cmi'],
  ['ใบขับชี่', 'driving_license'],
  ['ภาษีรด', 'vehicle_tax'],
  ['บัตรปชช หมด 1/1/72', 'national_id'],
  ['ตรอ', 'vehicle_inspection'],
  ['เวิร์คเพอร์มิท', 'work_permit'],

  // ไม่เว้นวรรค — ภาษาไทยไม่มีขอบคำให้ตัด
  ['วีซ่าหมดอายุ12ตุลา70', 'visa'],
  ['ประกันสังคมม39', 'social_security'],

  // คำที่ใกล้กันต้องไม่แย่งกัน
  ['ประกันสุขภาพ 1/1/70', 'health_insurance'],
  ['ประกันชีวิต', 'life_insurance'],
  ['ประกันสังคม', 'social_security'],
  ['ประกันรถยนต์ชั้น 1', 'motor_insurance'],
];

for (const [text, key] of HITS) {
  test(`อ่าน "${text}" เป็น ${key}`, () => {
    assert.equal(matchDocType(text), key);
  });
}

/**
 * ยอมพลาดทางไม่รู้จัก ดีกว่าเดาผิดแล้วตั้งเตือนผิดใบ
 * ถ้าไม่ชัด ระบบจะไปถามผู้ใช้เอง ซึ่งเสียเวลาหนึ่งจังหวะ ไม่ใช่เสียเงินค่าปรับ
 */
const MISSES = [
  'สวัสดีครับ',
  'ราคาเท่าไหร่',
  'ขอบคุณมากครับ',
  '12/10/2570',
  'ลบข้อมูลทั้งหมด',
  'อยากคุยกับคน',
  'วันนี้ฝนตกมาก',
  'ขอใบเสร็จด้วยครับ',
];

for (const text of MISSES) {
  test(`ไม่เดาประเภทจาก "${text}"`, () => {
    assert.equal(matchDocType(text), null);
  });
}
