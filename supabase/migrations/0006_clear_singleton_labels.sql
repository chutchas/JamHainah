-- ============================================================
-- 0006 — ล้าง label ของเอกสารที่คนหนึ่งมีได้ใบเดียว
--
-- label มีไว้แยกว่าเป็น "ใบไหน" เช่นทะเบียนรถ
-- เอกสารประจำตัวมีใบเดียวอยู่แล้ว จึงไม่มีอะไรให้แยก
-- ที่ผ่านมา OCR ใส่ชื่อเอกสารมาเป็น label ทำให้แสดงผลซ้ำซ้อน
-- เช่น "บัตรประชาชน · บัตรประจำตัวประชาชน"
--
-- โค้ดกันที่ต้นทางแล้ว (repo.createDocument) อันนี้เก็บกวาดของเดิม
-- ============================================================

update public.documents
   set label = null
 where doc_type in ('national_id', 'driving_license', 'passport', 'social_security')
   and label is not null;
