-- 0016 — เพิ่มระดับ "หัวหน้า"
--
-- สองระดับเดิมบังคับให้เลือกอย่างใดอย่างหนึ่งที่ไม่ตรงกับความจริง:
-- ให้เป็น owner = แตะสิทธิ์คนอื่นได้ทั้งหมด · ให้เป็น staff = เห็นราคาไม่ได้
-- ทั้งที่คนที่คุมคิวจริงต้องเห็นเงิน แต่ไม่ควรถอดสิทธิ์ใครได้
--
-- ไม่ต้องย้ายข้อมูล — แถวเดิมเป็น owner กับ staff ซึ่งยังใช้ได้ทั้งคู่
-- ============================================================

alter table public.admins drop constraint if exists admins_role_check;
alter table public.admins add constraint admins_role_check
  check (role in ('owner', 'manager', 'staff'));
