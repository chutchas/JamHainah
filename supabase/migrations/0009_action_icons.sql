-- 💻 (โน้ตบุ๊ก) เป็น emoji ที่ระบบปฏิบัติการวาดต่างกันมาก
-- บาง Android ออกมาเป็นกล่องสีเทาทึบ อ่านไม่ออกว่าคืออะไร
-- 🌐 เป็นรูปทรงง่าย ๆ วงกลมมีเส้น เหมือนกันแทบทุกเครื่อง
-- และสื่อว่า "ทำบนเว็บ" ตรงกว่าโน้ตบุ๊กด้วย
-- ------------------------------------------------------------
update public.renew_actions
set label = replace(label, '💻 ', '🌐 ')
where label like '💻 %';
